function formatAxisRate(value,points) {
  const digits=Math.max(2,Math.min(6,...points.map(point=>(String(point.rate).split(".")[1] || "").length)));
  return new Intl.NumberFormat(locale(),{minimumFractionDigits:digits,maximumFractionDigits:digits}).format(value);
}
const formatMoney = (value,currency) => new Intl.NumberFormat(locale(),{style:"currency",currency,maximumFractionDigits:2}).format(Number(value));
