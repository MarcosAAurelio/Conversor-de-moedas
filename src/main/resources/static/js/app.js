function parseDate(value) { return new Date(String(value).length === 10 ? value + "T12:00:00" : value); }
function formatDate(value,withTime=false) {
  const options=withTime?{dateStyle:"medium",timeStyle:"short"}:{day:"2-digit",month:"short",year:"numeric"};
  return new Intl.DateTimeFormat(locale(),options).format(parseDate(value));
}
